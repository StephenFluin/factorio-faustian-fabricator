    type = "recipe",
    name = "idle-dummy-recipe",
    icon = "__faustian-fabricator__/graphics/icons/faustian-fabricator.png",
    icon_size = 64,
    enabled = true,
    hidden = true,
    energy_required = 1,
    ingredients = {},
    results = {}
}
